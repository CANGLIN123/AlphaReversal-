def classify_by_code(code):
    """代码精确匹配 + 前缀启发"""
    num = code[:6]
    if num in KNOWN_INDUSTRIES:
        return KNOWN_INDUSTRIES[num]
    if num.startswith('688'):
        return '电子'
    if num.startswith('300'):
        return '医药生物'
    if num.startswith(('600','601','603','605')):
        return '机械设备'  # 上交所主板默认
    return '其他'

