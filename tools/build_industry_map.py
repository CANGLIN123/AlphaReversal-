# 主流程
# ============================================
if __name__ == '__main__':
    import sys

    # 先试API
    if '--api' in sys.argv:
        try:
            df = download_from_api()
            print("Done!")
            sys.exit(0)
        except Exception as e:
            print(f"[API failed] {e}")
            print("Falling back to code-based classification...")

    # 代码段分类
    stocks = sorted(set(
        f.name[:9] for f in cache_dir.glob("*.csv")
        if not f.name.startswith(("IDX_", "stock_pool_", "FUNDA_"))
        and "_qfq" in f.name
    ))

    mapping = {}
    for code in stocks:
        mapping[code] = classify_by_code(code)

    cnt = Counter(mapping.values())
    print(f"\nTotal: {len(stocks)} stocks")
    print(f"Industries: {len(cnt)}")
    print("\nTop 15:")
    for ind, c in cnt.most_common(15):
        print(f"  {ind}: {c}")

    df = pd.DataFrame([{'ts_code': k, 'industry': v} for k, v in mapping.items()])
    df.to_csv(cache_dir / "stock_industry.csv", index=False)
    print(f"\nSaved: cache/stock_industry.csv")
    print("Run with --api flag when rate limit resets to get official data.")
